#!/usr/bin/env python3
"""Build a searchable source/route index without importing application code."""

import argparse
import ast
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "CODE_CATALOG.md"


def sources():
    """Select repository sources, excluding ignored runtime and private data."""
    names = subprocess.check_output(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT,
        text=True,
    ).splitlines()
    return sorted(
        {
            name
            for name in names
            if name.endswith(".py")
            or (
                name.startswith("executive-dashboard/")
                and "/vendor/" not in name
                and Path(name).suffix in {".ts", ".tsx", ".css", ".mjs", ".cjs"}
            )
        }
    )


def render():
    """Derive modules, top-level symbols and literal routes from source syntax."""
    lines = [
        "# Code catalog",
        "",
        "Generated by `scripts/code_catalog.py`; edit source docstrings, then regenerate.",
        "This index reads syntax only. It does not start the app, load .env or read the database.",
        "See [the developer guide](DEVELOPMENT.md) for architecture and debugging.",
        "",
    ]
    routes = []
    for name in sources():
        path = ROOT / name
        lines.extend([f"## [{name}](../{name})", ""])
        if path.suffix != ".py":
            lines.extend(
                [
                    "Dashboard source; component/library responsibility follows its filename.",
                    "",
                ]
            )
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"))
        doc = ast.get_docstring(tree)
        if not doc:
            raise ValueError(f"Missing module documentation: {name}")
        lines.extend([doc.splitlines()[0], ""])
        symbols = []
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                summary = ast.get_docstring(node)
                suffix = f": {summary.splitlines()[0]}" if summary else ""
                symbols.append(f"- `{node.name}`{suffix}")
                for decorator in getattr(node, "decorator_list", []):
                    if (
                        isinstance(decorator, ast.Call)
                        and isinstance(decorator.func, ast.Attribute)
                        and decorator.func.attr
                        in {"get", "post", "put", "patch", "delete"}
                        and decorator.args
                        and isinstance(decorator.args[0], ast.Constant)
                        and isinstance(decorator.args[0].value, str)
                    ):
                        routes.append(
                            (
                                decorator.func.attr.upper(),
                                decorator.args[0].value,
                                name,
                                node.name,
                            )
                        )
        lines.extend(symbols or ["Module constants/imports only."])
        lines.append("")
    lines.extend(
        [
            "## API route lookup",
            "",
            "Routes still require the application's authentication dependencies; this list grants no authority.",
            "",
            "| Method | Path | Handler |",
            "|---|---|---|",
        ]
    )
    for method, path, name, handler in sorted(routes):
        lines.append(f"| {method} | `{path}` | [{name}](../{name}) · `{handler}` |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if the saved catalog is stale"
    )
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit(
                "Code catalog is stale: run .venv/bin/python scripts/code_catalog.py"
            )
        print("Code catalog is current")
    else:
        OUTPUT.parent.mkdir(exist_ok=True)
        OUTPUT.write_text(content, encoding="utf-8")
        print("Updated docs/CODE_CATALOG.md")


if __name__ == "__main__":
    main()
