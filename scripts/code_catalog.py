#!/usr/bin/env python3
"""Build a compact, searchable source/route index without importing application code."""

import argparse
import ast
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "CODE_CATALOG.md"


def sources(scope="all"):
    """Select existing Git-visible sources, excluding ignored runtime/private data."""
    names = subprocess.check_output(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT,
        text=True,
    ).splitlines()
    result = set()
    for name in names:
        frontend = (
            name.startswith("executive-dashboard/")
            and "/vendor/" not in name
            and Path(name).suffix in {".ts", ".tsx", ".css", ".mjs", ".cjs"}
        )
        python = name.endswith(".py")
        tests = name.startswith("tests/")
        if (
            (python or frontend)
            and (ROOT / name).is_file()
            and (
                scope == "all"
                or (scope == "frontend" and frontend)
                or (scope == "tests" and tests)
                or (scope == "backend" and python and not tests)
            )
        ):
            result.add(name)
    return sorted(result)


def render(scope="all"):
    """One row per module plus literal routes, including nested router factories."""
    lines = [
        "# Code catalog",
        "",
        "Generated by `scripts/code_catalog.py`; refresh the full index or print `--scope backend|frontend|tests`.",
        "Reads syntax only; no app, .env or database imports. Use `rg` for individual symbols.",
        "See [the developer guide](DEVELOPMENT.md).",
        "",
        "| Module | Responsibility |",
        "|---|---|",
    ]
    routes = []
    for name in sources(scope):
        path = ROOT / name
        if path.suffix == ".py":
            tree = ast.parse(path.read_text(encoding="utf-8"))
            doc = ast.get_docstring(tree)
            if not doc:
                raise ValueError(f"Missing module documentation: {name}")
            summary = doc.splitlines()[0][:140]
            for node in ast.walk(tree):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    for decorator in node.decorator_list:
                        if (
                            isinstance(decorator, ast.Call)
                            and isinstance(decorator.func, ast.Attribute)
                            and decorator.func.attr
                            in {"get", "post", "put", "patch", "delete"}
                            and decorator.args
                            and isinstance(decorator.args[0], ast.Constant)
                            and isinstance(decorator.args[0].value, str)
                        ):
                            routes.append(
                                (
                                    decorator.func.attr.upper(),
                                    decorator.args[0].value,
                                    name,
                                    node.name,
                                )
                            )
        else:
            summary = "Dashboard component, library or style; see filename and source."
        lines.append(f"| [{name}](../{name}) | {summary.replace('|', '/')} |")
    lines += [
        "",
        "## API route lookup",
        "",
        "Routes retain authentication and approval requirements; this index grants no authority.",
        "",
        "| Method | Path | Handler |",
        "|---|---|---|",
    ]
    for method, path, name, handler in sorted(routes):
        lines.append(f"| {method} | `{path}` | [{name}](../{name}) · `{handler}` |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if the saved full catalog is stale"
    )
    parser.add_argument(
        "--scope", choices=["all", "backend", "frontend", "tests"], default="all"
    )
    args = parser.parse_args()
    if args.check and args.scope != "all":
        parser.error("--check verifies the saved full catalog; omit --scope")
    content = render(args.scope)
    if args.scope != "all":
        print(content, end="")
    elif args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit(
                "Code catalog is stale: run .venv/bin/python scripts/code_catalog.py"
            )
        print("Code catalog is current")
    else:
        OUTPUT.parent.mkdir(exist_ok=True)
        OUTPUT.write_text(content, encoding="utf-8")
        print("Updated docs/CODE_CATALOG.md")


if __name__ == "__main__":
    main()
